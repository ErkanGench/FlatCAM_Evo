"""PcbWizard INF parsing and Excellon header generation. No Qt."""

import re


def parse_inf(lines):
    """Return the tool table and the ordered format declarations."""
    tool_re = re.compile(r'^T(\d+)\s+(\d*\.?\d+)$')
    format_re = re.compile(r'^(\d+)\.?(\d+)\s*format,\s*(inches|metric)?,\s*(absolute|incremental)?.*$')
    tools = {}
    formats = []
    for line in lines:
        line = line.strip(' \r\n')
        match = tool_re.search(line)
        if match:
            tools[int(match.group(1))] = float(match.group(2))
            continue
        match = format_re.search(line)
        if match:
            formats.append((int(match.group(1)), int(match.group(2)),
                            'INCH' if match.group(3) == 'inches' else 'METRIC'))
    return tools, formats


def merge_excellon(lines, tools, integral, fractional, units, zeros, version, version_date, time_str):
    """Insert the INF tool table and selected format after each M48 header."""
    excellon_string = ''
    for line in lines:
        excellon_string += line
        if 'M48' in line:
            header = ';EXCELLON RE-GENERATED BY FLATCAM v%s - www.flatcam.org - Version Date: %s\n' % \
                      (str(version), str(version_date))
            header += ';Created on : %s' % time_str + '\n'
            header += ';FILE_FORMAT={integral}:{fractional}\n'.format(integral=integral, fractional=fractional)
            header += '{units},{zeros}\n'.format(units=units, zeros=zeros)
            for k, v in tools.items():
                header += 'T{tool}C{dia}\n'.format(tool=int(k), dia=float(v))
            excellon_string += header
    return excellon_string
